# ---------------------------------------------------------------- language


_PATH_LANGS = {"ja", "en", "ko", "zh-CN", "zh-TW", "fr", "de", "es"}
_STEM_LANG = re.compile(r"[-._](ja|en)$")
_KANA = re.compile(r"[\u3040-\u30ff]")
_ASCII_LETTER = re.compile(r"[A-Za-z]")
# Kana as a share of kana plus ASCII letters. Japanese prose here measures 0.3 or more even when
# dense with commands and product names; an English file quoting Japanese examples measures under
# 0.01. A bare kana count read such files as Japanese and applied the Japanese rules to English.
_KANA_SHARE = 0.05


def language_of(relpath: str, text: str) -> str:
    """The document's language: a path component, then a `-ja`/`.en` stem suffix, then the text."""
    parts = Path(relpath).parts
    for part in parts[:-1]:
        if part in _PATH_LANGS:
            return part
    suffix = _STEM_LANG.search(Path(relpath).stem)
    if suffix:
        return suffix.group(1)
    kana = len(_KANA.findall(text))
    letters = len(_ASCII_LETTER.findall(text))
    return "ja" if kana >= 10 and kana >= _KANA_SHARE * (kana + letters) else "en"


# ---------------------------------------------------------------- shared preprocessing


def _blank_frontmatter(lines: list[str]) -> list[str]:
    """Frontmatter is metadata, not prose. Blanked so line numbers stay those of the file."""
    if not lines or lines[0].strip() != "---":
        return lines
    for index in range(1, len(lines)):
        if lines[index].strip() == "---":
            return [""] * (index + 1) + lines[index + 1 :]
    return lines


def _mask_code_spans(line: str) -> str:
    """Replace each code span, backticks included, with spaces of the same width."""
    out: list[str] = []
    i = 0
    n = len(line)
    while i < n:
        if line[i] != "`":
            out.append(line[i])
            i += 1
            continue
        j = i
        while j < n and line[j] == "`":
            j += 1
        run = j - i
        k = j
        close = -1
        while k < n:
            if line[k] == "`":
                m = k
                while m < n and line[m] == "`":
                    m += 1
                if m - k == run:
                    close = m
                    break
                k = m
            else:
                k += 1
        if close < 0:
            out.append(line[i:j])
            i = j
        else:
            out.append(" " * (close - i))
            i = close
    return "".join(out)


@dataclass
class _Line:
    number: int
    raw: str
    masked: str  # prose only: code spans, comments and URLs replaced with spaces
    kind: str  # skip / blank / code / heading / list / table / para
    level: int = 0  # heading level


def _prose_view(lines: list[str]) -> list[_Line]:
    """Classify each line and mask what is not prose, for every rule except D1."""
    view: list[_Line] = []
    fence: str | None = None
    in_comment = False
    in_switcher = False
    for number, raw in enumerate(lines, start=1):
        fence_match = FENCE.match(raw)
        if fence is not None:
            if fence_match:
                candidate = fence_match.group(1)
                if (
                    candidate[0] == fence[0]
                    and len(candidate) >= len(fence)
                    and set(raw.strip()) == {fence[0]}
                ):
                    fence = None
            view.append(_Line(number, raw, "", "code"))
            continue
        if fence_match and not in_comment:
            fence = fence_match.group(1)
            view.append(_Line(number, raw, "", "code"))
            continue
        if SWITCHER_START in raw:
            in_switcher = True
        if in_switcher:
            if SWITCHER_END in raw:
                in_switcher = False
            view.append(_Line(number, raw, "", "skip"))
            continue
        masked = _mask_code_spans(raw)
        chars = list(masked)
        position = 0
        while position < len(masked):
            if in_comment:
                end = masked.find("-->", position)
                stop = len(masked) if end < 0 else end + 3
                for index in range(position, stop):
                    chars[index] = " "
                if end < 0:
                    break
                in_comment = False
                position = stop
                continue
            start = masked.find("<!--", position)
            if start < 0:
                break
            in_comment = True
            position = start
        masked = URL.sub(lambda m: " " * len(m.group()), "".join(chars))
        body = QUOTE_PREFIX.sub("", masked)
        if not masked.strip():
            view.append(_Line(number, raw, "", "blank" if not raw.strip() else "skip"))
            continue
        heading = HEADING.match(body)
        if heading:
            view.append(_Line(number, raw, body, "heading", len(heading.group(1))))
        elif LIST_ITEM.match(body):
            view.append(_Line(number, raw, body, "list"))
        elif body.lstrip().startswith("|"):
            view.append(_Line(number, raw, body, "table"))
        else:
            view.append(_Line(number, raw, body, "para"))
    return view


def _first_visible_after_marker(line: _Line) -> str:
    if line.kind == "heading":
        rest = line.masked.lstrip()[line.level :]
    else:
        match = LIST_ITEM.match(line.masked)
        rest = line.masked[match.end() :] if match else ""
        rest = re.sub(r"^\[[ xX]\]\s*", "", rest)
    rest = rest.lstrip()
    return rest[:1]


def _structural_findings(view: list[_Line], lang: str) -> list[Finding]:
    found: list[Finding] = []

    def add(rule_id: str, line: int, message: str | None = None) -> None:
        rule = RULE_BY_ID[rule_id]
        found.append(Finding(line, rule_id, rule.level, message or rule.message))

    content = [line for line in view if line.kind not in ("skip", "blank")]
    for line in view:
        if line.kind in ("skip", "blank", "code"):
            continue
        text = line.masked.rstrip()
        for rule_id, by_lang in LINE_PATTERNS.items():
            pattern = by_lang.get(lang)
            if pattern is None or lang not in RULE_BY_ID[rule_id].langs:
                continue
            if rule_id == "D11" and URL.search(line.raw):
                continue
            if pattern.search(text):
                add(rule_id, line.number)
        if NUMBERED_ITEM.match(text) and D10_PATTERNS[lang].search(text):
            add("D10", line.number)
        if lang == "ja" and line.kind == "list" and D12_PATTERN.search(text):
            add("D12", line.number)
        if line.kind in ("list", "heading") and EMOJI.match(
            _first_visible_after_marker(line)
        ):
            add("D13", line.number)
        if line.kind == "heading" and ("**" in text or "__" in text):
            add("D14", line.number)
        if line.kind == "para" and D15_LINE.match(text.strip()):
            add("D15", line.number)
        dashes = text.count("\u2014")
        if dashes:
            add(
                "D18",
                line.number,
                f"{RULE_BY_ID['D18'].message} ({dashes} on this line)",
            )

    # D15 (a): bold density over the whole document.
    visible = sum(len(re.sub(r"\s", "", line.masked)) for line in content)
    spans = sum(len(D15_SPAN.findall(line.masked)) for line in content)
    if visible >= D15_MIN_CHARS and spans * 1000 / visible > D15_MAX_PER_1000:
        add(
            "D15",
            1,
            f"bold density {spans * 1000 / visible:.1f} per 1,000 characters "
            f"(over {D15_MAX_PER_1000})",
        )

    # D17 (a): a top-level list holding a single item. (b): a heading followed directly by a
    # deeper heading, with nothing in between.
    def item_indent(line: _Line) -> int | None:
        match = LIST_ITEM.match(line.masked) if line.kind == "list" else None
        return len(match.group(1)) if match else None

    def indent_of(line: _Line) -> int:
        body = QUOTE_PREFIX.sub("", line.raw)
        return len(body) - len(body.lstrip())

    index = 0
    while index < len(view):
        base = item_indent(view[index])
        if base is None or base > 3:
            index += 1
            continue
        start = view[index].number
        items = 1
        index += 1
        while index < len(view):
            current = view[index]
            sibling = item_indent(current)
            if current.kind == "blank":
                following = next(
                    (v for v in view[index + 1 :] if v.kind != "blank"), None
                )
                if following is None:
                    break
                following_item = item_indent(following)
                if not (
                    following_item is not None
                    and abs(following_item - base) <= 1
                    or indent_of(following) >= base + 2
                ):
                    break
            elif current.kind == "heading" or (
                current.kind in ("code", "skip") and indent_of(current) < base + 2
            ):
                break
            elif sibling is not None and abs(sibling - base) <= 1:
                items += 1
            index += 1
        if items == 1:
            add("D17", start)
    for position, line in enumerate(content):
        if line.kind != "heading" or position + 1 >= len(content):
            continue
        following = content[position + 1]
        if following.kind == "heading" and following.level > line.level:
            add("D17", line.number, "heading with no content before a deeper heading")

    # D19: a Japanese sentence that stops at a colon right before a block.
    if lang == "ja":
        for position, line in enumerate(view):
            if line.kind not in ("para", "list") or not D19_PATTERN.search(line.masked):
                continue
            following = next((v for v in view[position + 1 :] if v.raw.strip()), None)
            if following is not None and (
                FENCE.match(following.raw)
                or LIST_ITEM.match(following.raw)
                or following.raw.lstrip().startswith("|")
            ):
                add("D19", line.number)
    return found


