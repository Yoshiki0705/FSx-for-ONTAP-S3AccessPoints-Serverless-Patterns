# markdown-it 14.1.1 `isWhiteSpace`, which is narrower than Unicode Zs plus the ASCII controls.
_WHITESPACE = frozenset(
    "\t\n\x0b\x0c\r \xa0\u1680\u202f\u205f\u3000"
    + "".join(chr(c) for c in range(0x2000, 0x200B))
)
_ASCII_PUNCT = frozenset("!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~")


def _is_punct(char: str) -> bool:
    """markdown-it `isMdAsciiPunct || isPunctChar` (Unicode P and S).

    markdown-it reads one UTF-16 code unit, so a character outside the BMP is a lone surrogate to
    it and is neither punctuation nor whitespace. That is mirrored here: an emoji next to `**` is
    a letter for flanking purposes, whatever its Unicode category.
    """
    if char in _ASCII_PUNCT:
        return True
    if ord(char) > 0xFFFF:
        return False
    return unicodedata.category(char)[0] in "PS"


_ATTR = r"(?:\s+[a-zA-Z_:][a-zA-Z0-9:._-]*(?:\s*=\s*(?:[^\"'=<>`\x00-\x20]+|'[^']*'|\"[^\"]*\"))?)"
_OPEN_TAG = r"<[A-Za-z][A-Za-z0-9\-]*" + _ATTR + r"*\s*/?>"
_CLOSE_TAG = r"</[A-Za-z][A-Za-z0-9\-]*\s*>"
HTML_TAG = re.compile(
    r"(?:" + _OPEN_TAG + "|" + _CLOSE_TAG + r"|<!---?>|<!--(?:[^-]|-[^-]|--[^>])*-->"
    r"|<[?][\s\S]*?[?]>|<![A-Za-z][^>]*>|<!\[CDATA\[[\s\S]*?\]\]>)"
)
HTML_OPEN_CLOSE = re.compile(r"(?:" + _OPEN_TAG + "|" + _CLOSE_TAG + r")")
AUTOLINK = re.compile(r"<[a-zA-Z][a-zA-Z0-9+.\-]{1,31}:[^<>\x00-\x20]*>")
EMAIL_AUTOLINK = re.compile(
    r"<[a-zA-Z0-9.!#$%&'*+/=?^_`{|}~-]+@[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?"
    r"(?:\.[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?)*>"
)
ENTITY = re.compile(
    r"&(?:#[xX][0-9a-fA-F]{1,6}|#[0-9]{1,7}|[A-Za-z][A-Za-z0-9]{1,31});"
)
_BLOCK_NAMES = (
    "address|article|aside|base|basefont|blockquote|body|caption|center|col|colgroup|dd|details|"
    "dialog|dir|div|dl|dt|fieldset|figcaption|figure|footer|form|frame|frameset|h1|h2|h3|h4|h5|"
    "h6|head|header|hr|html|iframe|legend|li|link|main|menu|menuitem|nav|noframes|ol|optgroup|"
    "option|p|param|search|section|summary|table|tbody|td|tfoot|th|thead|title|tr|track|ul"
)
HTML_BLOCKS: tuple[tuple[re.Pattern[str], re.Pattern[str] | None, bool], ...] = (
    (
        re.compile(r"^<(script|pre|style|textarea)(?=(\s|>|$))", re.IGNORECASE),
        re.compile(r"</(script|pre|style|textarea)>", re.IGNORECASE),
        True,
    ),
    (re.compile(r"^<!--"), re.compile(r"-->"), True),
    (re.compile(r"^<\?"), re.compile(r"\?>"), True),
    (re.compile(r"^<![A-Z]"), re.compile(r">"), True),
    (re.compile(r"^<!\[CDATA\["), re.compile(r"\]\]>"), True),
    (
        re.compile(r"^</?(" + _BLOCK_NAMES + r")(?=(\s|/?>|$))", re.IGNORECASE),
        None,
        True,
    ),
    (re.compile(r"^(?:" + _OPEN_TAG + "|" + _CLOSE_TAG + r")\s*$"), None, False),
)
THEMATIC_BREAK = re.compile(
    r"^ {0,3}(?:(?:\*[ \t]*){3,}|(?:-[ \t]*){3,}|(?:_[ \t]*){3,})$"
)
SETEXT = re.compile(r"^ {0,3}(?:=+|-+)[ \t]*$")
ATX = re.compile(r"^ {0,3}(#{1,6})(?:[ \t]+(.*?))?(?:[ \t]+#+)?[ \t]*$")
FENCE_OPEN = re.compile(r"^ {0,3}(`{3,}|~{3,})(.*)$")
BULLET = re.compile(r"^( {0,3})([*+-])([ \t]+|$)")
ORDERED = re.compile(r"^( {0,3})(\d{1,9})([.)])([ \t]+|$)")
REFERENCE = re.compile(r"^ {0,3}\[((?:[^\]\\]|\\.)+)\]:")


def _norm_label(label: str) -> str:
    return " ".join(label.split()).casefold()


def _indent(text: str) -> int:
    return len(text) - len(text.lstrip(" "))


def _list_marker(rest: str):
    """(width, empty, ordered_start) for a list marker at the start of `rest`, else None."""
    if THEMATIC_BREAK.match(rest):
        return None
    match = BULLET.match(rest) or ORDERED.match(rest)
    if not match:
        return None
    marker_end = match.end(len(match.groups()) - 1)
    spaces = match.group(len(match.groups()))
    empty = not rest[match.end() :].strip()
    if empty or len(spaces) > 4:
        width = marker_end + 1
    else:
        width = marker_end + len(spaces)
    start = int(match.group(2)) if match.re is ORDERED else None
    return width, empty, start


def _html_block_type(rest: str) -> int | None:
    if _indent(rest) >= 4:
        return None
    text = rest.lstrip(" ")
    if not text.startswith("<"):
        return None
    for index, (opener, _closer, _interrupts) in enumerate(HTML_BLOCKS):
        if opener.search(text):
            return index
    return None


def _interrupts_paragraph(rest: str) -> bool:
    """Whether `rest` starts a block that ends an open paragraph (lazy lines use this too)."""
    if not rest.strip():
        return True
    if _indent(rest) >= 4:
        return False
    if (
        ATX.match(rest)
        or FENCE_OPEN.match(rest)
        or rest.lstrip(" ").startswith(">")
        or THEMATIC_BREAK.match(rest)
    ):
        return True
    html_type = _html_block_type(rest)
    if html_type is not None and HTML_BLOCKS[html_type][2]:
        return True
    marker = _list_marker(rest)
    return bool(marker and not marker[1] and marker[2] in (None, 1))


def _split_cells(row: str) -> list[str]:
    """markdown-it `escapedSplit`, with the leading and trailing empty cell dropped."""
    cells: list[str] = []
    current = ""
    last = 0
    escaped = False
    for pos, char in enumerate(row):
        if char == "|":
            if not escaped:
                cells.append(current + row[last:pos])
                current = ""
                last = pos + 1
            else:
                current += row[last : pos - 1]
                last = pos
        escaped = char == "\\"
    cells.append(current + row[last:])
    if cells and cells[0] == "":
        cells.pop(0)
    if cells and cells[-1] == "":
        cells.pop()
    return cells


def _delimiter_row_columns(row: str) -> int | None:
    text = row.strip()
    if not text or text[0] not in "|-:" or len(text) < 2:
        return None
    if text[1] not in "|-: \t" or (text[0] == "-" and text[1] in " \t"):
        return None
    if any(char not in "|-: \t" for char in text):
        return None
    columns = row.split("|")
    count = 0
    for index, column in enumerate(columns):
        cell = column.strip()
        if not cell:
            if index in (0, len(columns) - 1):
                continue
            return None
        if not re.fullmatch(r":?-+:?", cell):
            return None
        count += 1
    return count


def _match_containers(raw: str, stack: list[tuple[str, int]]) -> tuple[int, int]:
    """How many open containers this line continues, and where its content starts."""
    pos = 0
    for depth, (kind, width) in enumerate(stack):
        rest = raw[pos:]
        if kind == "quote":
            match = re.match(r" {0,3}>", rest)
            if not match:
                return depth, pos
            pos += match.end()
            if raw[pos : pos + 1] == " ":
                pos += 1
        else:
            if not rest.strip():
                continue
            if _indent(rest) < width:
                return depth, pos
            pos += width
    return len(stack), pos


def _blocks(lines: list[str]) -> list[tuple[str, list[tuple[int, str]]]]:
    """Split a document into ("inline" | "raw", [(line number, text), ...]) blocks.

    The container and leaf rules are the subset of CommonMark this repository's documents use:
    block quotes, lists, fences, indented code, ATX and setext headings, thematic breaks, HTML
    blocks, GFM tables and paragraphs. Indented code inside a list item, and reference definitions
    spanning several lines, are approximations.
    """
    out: list[tuple[str, list[tuple[int, str]]]] = []
    stack: list[tuple[str, int]] = []
    leaf: dict | None = None

    def close() -> None:
        nonlocal leaf
        if leaf is None:
            return
        if leaf["kind"] == "para" and leaf["lines"]:
            out.append(("inline", leaf["lines"]))
        elif leaf["kind"] == "html":
            out.append(("raw", leaf["lines"]))
        leaf = None

    total = len(lines)
    index = 0
    while index < total:
        number = index + 1
        raw = lines[index].expandtabs(4)
        matched, pos = _match_containers(raw, stack)
        rest = raw[pos:]
        blank = not rest.strip()

        if matched < len(stack):
            if (
                leaf is not None
                and leaf["kind"] == "para"
                and not _interrupts_paragraph(rest)
            ):
                leaf["lines"].append((number, rest.strip()))
                index += 1
                continue
            close()
            del stack[matched:]
        elif leaf is not None and leaf["kind"] == "fence":
            text = rest.lstrip(" ")
            if (
                _indent(rest) < 4
                and text.startswith(leaf["marker"][0] * len(leaf["marker"]))
                and set(text.rstrip()) == {leaf["marker"][0]}
            ):
                leaf = None
            index += 1
            continue
        elif leaf is not None and leaf["kind"] == "html":
            closer = HTML_BLOCKS[leaf["type"]][1]
            if closer is None:
                if blank:
                    close()
                    index += 1
                    continue
                leaf["lines"].append((number, rest))
            else:
                leaf["lines"].append((number, rest))
                if closer.search(rest):
                    close()
            index += 1
            continue
        elif leaf is not None and leaf["kind"] == "table":
            if not blank and _indent(rest) < 4 and not _interrupts_paragraph(rest):
                cells = _split_cells(rest.strip())
                for cell in cells[: leaf["columns"]]:
                    out.append(("inline", [(number, cell.strip())]))
                index += 1
                continue
            leaf = None
        elif leaf is not None and leaf["kind"] == "code":
            if blank or _indent(rest) >= 4:
                index += 1
                continue
            leaf = None

        # New containers.
        while True:
            if _indent(rest) >= 4:
                break
            stripped = rest.lstrip(" ")
            if stripped.startswith(">"):
                close()
                stack.append(("quote", 0))
                rest = stripped[1:]
                rest = rest.removeprefix(" ")
                continue
            marker = _list_marker(rest)
            if marker is None:
                break
            width, empty, start = marker
            if (
                leaf is not None
                and leaf["kind"] == "para"
                and (empty or start not in (None, 1))
            ):
                break
            close()
            stack.append(("item", width))
            rest = rest[width:] if len(rest) >= width else ""
        blank = not rest.strip()

        if blank:
            close()
            index += 1
            continue
        if leaf is not None and leaf["kind"] == "para":
            if SETEXT.match(rest):
                close()
                index += 1
                continue
            if not _interrupts_paragraph(rest) and not _table_starts(
                lines, index, rest, stack
            ):
                leaf["lines"].append((number, rest.strip()))
                index += 1
                continue
        if _indent(rest) >= 4:
            close()
            leaf = {"kind": "code"}
            index += 1
            continue
        fence = FENCE_OPEN.match(rest)
        if fence and not (fence.group(1)[0] == "`" and "`" in fence.group(2)):
            close()
            leaf = {"kind": "fence", "marker": fence.group(1)}
            index += 1
            continue
        heading = ATX.match(rest)
        if heading:
            close()
            out.append(("inline", [(number, (heading.group(2) or "").strip())]))
            index += 1
            continue
        if THEMATIC_BREAK.match(rest):
            close()
            index += 1
            continue
        html_type = _html_block_type(rest)
        if html_type is not None and (HTML_BLOCKS[html_type][2] or leaf is None):
            close()
            closer = HTML_BLOCKS[html_type][1]
            if closer is not None and closer.search(rest):
                out.append(("raw", [(number, rest)]))
            else:
                leaf = {"kind": "html", "type": html_type, "lines": [(number, rest)]}
            index += 1
            continue
        columns = _table_starts(lines, index, rest, stack)
        if columns:
            close()
            for cell in _split_cells(rest.strip()):
                out.append(("inline", [(number, cell.strip())]))
            leaf = {"kind": "table", "columns": columns}
            index += 2
            continue
        if leaf is None and REFERENCE.match(rest):
            index += 1
            continue
        close()
        leaf = {"kind": "para", "lines": [(number, rest.strip())]}
        index += 1
    close()
    return out


def _table_starts(lines: list[str], index: int, rest: str, stack) -> int | None:
    """Column count when `rest` is a table header and the next line its delimiter row."""
    if "|" not in rest or index + 1 >= len(lines) or _indent(rest) >= 4:
        return None
    following = lines[index + 1].expandtabs(4)
    matched, pos = _match_containers(following, stack)
    if matched < len(stack):
        return None
    columns = _delimiter_row_columns(following[pos:])
    if not columns or _indent(following[pos:]) >= 4:
        return None
    header = _split_cells(rest.strip())
    return columns if len(header) == columns else None


def _reference_labels(lines: list[str]) -> set[str]:
    return {
        _norm_label(match.group(1))
        for line in lines
        if (match := REFERENCE.match(QUOTE_PREFIX.sub("", line.lstrip())))
    }


class _Inline:
    """The inline pass of markdown-it 14.1.1, reduced to what decides whether a `*` renders."""

    def __init__(self, src: str, refs: set[str]) -> None:
        self.src = src
        self.refs = refs
        self.items: list[list] = []  # [visible text, source index, delimiter or None]
        self.token = 0

    def emit(self, text: str, at: int) -> None:
        self.items.append([text, at, None])
        self.token += 1

    def scope(self, start: int, end: int) -> None:
        src = self.src
        delimiters: list[dict] = []
        pos = start
        while pos < end:
            char = src[pos]
            if char == "*":
                run_end = pos
                while run_end < end and src[run_end] == "*":
                    run_end += 1
                last = src[pos - 1] if pos > 0 else " "
                following = src[run_end] if run_end < end else " "
                last_punct, next_punct = _is_punct(last), _is_punct(following)
                last_space, next_space = last in _WHITESPACE, following in _WHITESPACE
                left = not next_space and (not next_punct or last_space or last_punct)
                right = not last_space and (not last_punct or next_space or next_punct)
                for at in range(pos, run_end):
                    delimiter = {
                        "length": run_end - pos,
                        "token": self.token,
                        "end": -1,
                        "open": left,
                        "close": right,
                        "matched": False,
                    }
                    delimiters.append(delimiter)
                    self.items.append(["*", at, delimiter])
                    self.token += 1
                pos = run_end
                continue
            if char == "\\" and pos + 1 < end:
                following = src[pos + 1]
                if following in _ASCII_PUNCT:
                    self.emit(following, pos + 1)
                    pos += 2
                    continue
                if following == "\n":
                    self.emit("\n", pos + 1)
                    pos += 2
                    continue
            if char == "`":
                run_end = pos
                while run_end < end and src[run_end] == "`":
                    run_end += 1
                run = run_end - pos
                scan = run_end
                closed = -1
                while scan < end:
                    found = src.find("`" * run, scan, end)
                    if found < 0:
                        break
                    tail = found + run
                    while tail < end and src[tail] == "`":
                        tail += 1
                    if tail - found == run:
                        closed = tail
                        break
                    scan = tail
                if closed < 0:
                    self.emit(src[pos:run_end], pos)
                    pos = run_end
                else:
                    self.emit(
                        "", pos
                    )  # code renders inside <code>, which the metric drops
                    pos = closed
                continue
            if char == "!" and src[pos + 1 : pos + 2] == "[":
                link = self.link(pos + 1, end)
                if link is not None:
                    self.emit(
                        "", pos
                    )  # alt text lives in an attribute, which is not visible
                    pos = link[2]
                    continue
            if char == "[":
                link = self.link(pos, end)
                if link is not None:
                    label_start, label_end, link_end = link
                    self.emit("", pos)
                    self.scope(label_start, label_end)
                    self.emit("", label_end)
                    pos = link_end
                    continue
            if char == "<":
                autolink = AUTOLINK.match(src, pos, end) or EMAIL_AUTOLINK.match(
                    src, pos, end
                )
                if autolink:
                    self.emit(autolink.group()[1:-1], pos)
                    pos = autolink.end()
                    continue
                tag = HTML_TAG.match(src, pos, end)
                if tag:
                    text = tag.group().lower()
                    if re.match(r"<(code|pre)[\s>]", text):
                        self.emit("\x01", pos)
                    elif re.match(r"</(code|pre)>", text):
                        self.emit("\x02", pos)
                    else:
                        self.emit("", pos)
                    pos = tag.end()
                    continue
            if char == "&":
                entity = ENTITY.match(src, pos, end)
                if entity:
                    decoded = html.unescape(entity.group())
                    if decoded != entity.group():
                        self.emit(decoded, pos)
                        pos = entity.end()
                        continue
            self.emit(char, pos)
            pos += 1
        _process_emphasis(delimiters)

    def link(self, pos: int, end: int) -> tuple[int, int, int] | None:
        """(label start, label end, link end) for an inline or defined reference link at `[`."""
        src = self.src
        level = 1
        scan = pos + 1
        while scan < end:
            char = src[scan]
            if char == "\\":
                scan += 2
                continue
            if char == "`":
                run_end = scan
                while run_end < end and src[run_end] == "`":
                    run_end += 1
                run = run_end - scan
                closing = src.find("`" * run, run_end, end)
                scan = closing + run if closing >= 0 else run_end
                continue
            if char == "[":
                level += 1
            elif char == "]":
                level -= 1
                if level == 0:
                    break
            scan += 1
        else:
            return None
        if level != 0:
            return None
        label_end = scan
        after = label_end + 1
        if after < end and src[after] == "(":
            depth = 0
            cursor = after + 1
            while cursor < end and src[cursor] in " \t\n":
                cursor += 1
            if cursor < end and src[cursor] == "<":
                close = src.find(">", cursor, end)
                if close < 0:
                    return None
                cursor = close + 1
            else:
                while cursor < end:
                    char = src[cursor]
                    if char == "\\" and cursor + 1 < end:
                        cursor += 2
                        continue
                    if char == "(":
                        depth += 1
                    elif char == ")":
                        if depth == 0:
                            break
                        depth -= 1
                    elif char in " \t\n":
                        break
                    cursor += 1
            while cursor < end and src[cursor] in " \t\n":
                cursor += 1
            if cursor < end and src[cursor] in "\"'(":
                quote = ")" if src[cursor] == "(" else src[cursor]
                close = cursor + 1
                while close < end and src[close] != quote:
                    close += 2 if src[close] == "\\" else 1
                if close >= end:
                    return None
                cursor = close + 1
                while cursor < end and src[cursor] in " \t\n":
                    cursor += 1
            if cursor < end and src[cursor] == ")":
                return pos + 1, label_end, cursor + 1
        if not self.refs:
            return None
        if after < end and src[after] == "[":
            close = src.find("]", after + 1, end)
            if close >= 0:
                reference = src[after + 1 : close] or src[pos + 1 : label_end]
                if _norm_label(reference) in self.refs:
                    return pos + 1, label_end, close + 1
                return None
        if _norm_label(src[pos + 1 : label_end]) in self.refs:
            return pos + 1, label_end, label_end + 1
        return None


def _process_emphasis(delimiters: list[dict]) -> None:
    """markdown-it `processDelimiters` for `*` only; marks every delimiter that becomes a tag."""
    bottoms = [-1] * 6
    header = 0
    last_token = -2
    jumps: list[int] = []
    for closer_index, closer in enumerate(delimiters):
        jumps.append(0)
        if last_token != closer["token"] - 1:
            header = closer_index
        last_token = closer["token"]
        if not closer["close"]:
            continue
        slot = (3 if closer["open"] else 0) + closer["length"] % 3
        minimum = bottoms[slot]
        opener_index = header - jumps[header] - 1
        new_minimum = opener_index
        while opener_index > minimum:
            opener = delimiters[opener_index]
            if opener["open"] and opener["end"] < 0:
                odd = False
                if (
                    (opener["close"] or closer["open"])
                    and (opener["length"] + closer["length"]) % 3 == 0
                    and (opener["length"] % 3 != 0 or closer["length"] % 3 != 0)
                ):
                    odd = True
                if not odd:
                    last_jump = (
                        jumps[opener_index - 1] + 1
                        if opener_index > 0 and not delimiters[opener_index - 1]["open"]
                        else 0
                    )
                    jumps[closer_index] = closer_index - opener_index + last_jump
                    jumps[opener_index] = last_jump
                    closer["open"] = False
                    opener["end"] = closer_index
                    opener["close"] = False
                    new_minimum = -1
                    last_token = -2
                    break
            opener_index -= jumps[opener_index] + 1
        if new_minimum != -1:
            bottoms[(3 if closer["open"] else 0) + closer["length"] % 3] = new_minimum
    for delimiter in delimiters:
        if delimiter["end"] >= 0:
            delimiter["matched"] = True
            delimiters[delimiter["end"]]["matched"] = True


_RAW_REMOVE = re.compile(
    r"<pre[\s>][\s\S]*?</pre>|<code[\s>][\s\S]*?</code>|<!--[\s\S]*?-->|<[^>]*>"
)
_RAW_ENTITY = re.compile(r"&#[xX]([0-9a-fA-F]+);|&#([0-9]+);|&(amp|lt|gt|quot|#39);")


def _raw_visible(block: list[tuple[int, str]]) -> list[tuple[str, int]]:
    """Visible characters of an HTML block: pre/code, comments and tags removed."""
    text = "\n".join(content for _, content in block)
    lines: list[int] = []
    for number, content in block:
        lines.extend([number] * (len(content) + 1))
    keep = [True] * len(text)
    for match in _RAW_REMOVE.finditer(text):
        for index in range(match.start(), match.end()):
            keep[index] = False
    return [(char, lines[index]) for index, char in enumerate(text) if keep[index]]


def unrendered_strong(text: str) -> list[int]:
    """Line number of every `**` that a CommonMark renderer leaves as visible asterisks.

    Defined as the count markdown-it's rendered HTML shows once <pre>, <code>, comments and tags
    are removed and entities decoded. Escaped `\\*\\*` is visible too, and counted.
    """
    lines = _blank_frontmatter(text.split("\n"))
    refs = _reference_labels(lines)
    visible: list[tuple[str, int]] = []
    for kind, block in _blocks(lines):
        if kind == "raw":
            visible.extend(_raw_visible(block))
        else:
            src = "\n".join(content for _, content in block)
            linemap: list[int] = []
            for number, content in block:
                linemap.extend([number] * (len(content) + 1))
            inline = _Inline(src, refs)
            inline.scope(0, len(src))
            hidden = False
            for shown, at, delimiter in inline.items:
                if shown == "\x01":
                    hidden = True
                    continue
                if shown == "\x02":
                    hidden = False
                    continue
                if hidden or (delimiter is not None and delimiter["matched"]):
                    continue
                for char in shown:
                    visible.append(
                        (char, linemap[at] if at < len(linemap) else block[-1][0])
                    )
        visible.append(("\n", 0))
    found: list[int] = []
    index = 0
    while index < len(visible) - 1:
        if visible[index][0] == "*" and visible[index + 1][0] == "*":
            found.append(visible[index][1])
            index += 2
        else:
            index += 1
    return found


