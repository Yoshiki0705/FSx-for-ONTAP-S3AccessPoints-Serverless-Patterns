#!/usr/bin/env python3
"""Writing-style signals for Markdown prose, in Japanese and English.

The criteria, the defect each rule points at, and the manual review that outranks every count are
in the Hub's criteria document:

    https://github.com/Yoshiki0705/FSx-for-ONTAP-Adoption-Playbook/blob/main/docs/agent/writing-quality.md

A count is a symptom. Removing the pattern without fixing what it indicates only makes the defect
harder to see, so treat a finding as a question about the sentence, not as an edit to make.

Two levels:

  fail     D1 (bold markers that do not render), D2 (Japanese closing catchphrases), D5 (chat-style
           closings), D14 (bold inside a heading). Staged: a repository gates on them with --fail
           in the same pull request that clears its existing findings.
  warning  everything else. Counted, never gated.

Copying: this file is self-contained (stdlib only, imports nothing from its repository). A sibling
repository copies this one file, runs it as a CLI, and links to the criteria document above rather
than copying the rules into its own guidance.

    python3 ai_style_rules.py docs/               # findings, exit 0
    python3 ai_style_rules.py docs/ --summary     # counts by category, language and rule
    python3 ai_style_rules.py docs/ --fail        # exit 1 when a fail-level rule fires
    python3 ai_style_rules.py --selftest          # every rule fires on its positive, not its negative

D1 decides whether a `**` renders by implementing the CommonMark delimiter-run and emphasis
algorithm, ported from markdown-it 14.1.1. The Hub checks it against fixtures generated by
markdown-it itself, because the case it exists for (`**「X」**` beside a Japanese particle) is one
that reads correctly in the source and renders as literal asterisks.
"""

