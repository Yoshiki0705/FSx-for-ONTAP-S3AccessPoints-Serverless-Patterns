def scan_markdown(text: str, lang: str) -> list[Finding]:
    """Every finding for one Markdown document, with 1-based line numbers of the file."""
    if lang not in LANGS:
        return []
    lines = _blank_frontmatter(text.split("\n"))
    found: list[Finding] = []
    d1 = RULE_BY_ID["D1"]
    for line in unrendered_strong(text):
        found.append(Finding(line, "D1", d1.level, d1.message))
    found.extend(_structural_findings(_prose_view(lines), lang))
    return sorted(found, key=lambda finding: (finding.line, finding.rule))


# The same marker syntax as the Hub's audit_public_output.py, which is authoritative inside the Hub.
# Duplicated here so this file stays copyable on its own. `ai-style-warn` precedes `ai-style` so
# the longer name is not read as the shorter one.
ALLOW = re.compile(r"<!--[^>]*?allow:(ai-style-warn|ai-style|all)[^>]*?-->")
FILE_ALLOW = re.compile(r"audit-file-allow:\s*([a-z-]+(?:\s*,\s*[a-z-]+)*)")
FILE_ALLOW_SCAN_LINES = 40
SKIP_DIR_NAMES = {"node_modules", ".venv", "venv", "__pycache__", "semantic-review"}


def _iter_markdown(paths: list[Path], excludes: list[str]):
    for given in paths:
        if given.is_file():
            yield given, given.name
            continue
        for path in sorted(given.rglob("*.md")):
            relative = path.relative_to(given)
            if any(
                part.startswith(".") or part in SKIP_DIR_NAMES
                for part in relative.parts[:-1]
            ):
                continue
            if any(
                fnmatch.fnmatch(relative.as_posix(), pattern) for pattern in excludes
            ):
                continue
            yield path, relative.as_posix()


def scan_file(path: Path, relative: str) -> tuple[str, list[Finding]]:
    """(language, findings) for one file, honouring allow markers."""
    text = path.read_text(encoding="utf-8")
    lines = text.split("\n")
    lang = language_of(relative, text)
    file_allowed: set[str] = set()
    for line in lines[:FILE_ALLOW_SCAN_LINES]:
        match = FILE_ALLOW.search(line)
        if match:
            file_allowed.update(part.strip() for part in match.group(1).split(","))
    kept: list[Finding] = []
    for finding in scan_markdown(text, lang):
        category = CATEGORY_FOR_LEVEL[finding.level]
        line = (
            _mask_code_spans(lines[finding.line - 1])
            if finding.line <= len(lines)
            else ""
        )
        allowed = {match.group(1) for match in ALLOW.finditer(line)} | file_allowed
        if category in allowed or "all" in allowed:
            continue
        kept.append(finding)
    return lang, kept


def summarize(results: list[tuple[str, str, list[Finding]]], top: int) -> str:
    counts: dict[tuple[str, str, str], int] = {}
    for _relative, lang, findings in results:
        for finding in findings:
            key = (CATEGORY_FOR_LEVEL[finding.level], lang, finding.rule)
            counts[key] = counts.get(key, 0) + 1
    order = {rule.id: index for index, rule in enumerate(RULES)}
    out = [
        "| category | lang | rule | findings |",
        "|---|---|---|---:|",
    ]
    for (category, lang, rule), count in sorted(
        counts.items(), key=lambda item: (item[0][0], item[0][1], order[item[0][2]])
    ):
        out.append(f"| {category} | {lang} | {rule} | {count} |")
    out.append("")
    scanned = {lang: 0 for lang in LANGS}
    for _relative, lang, _findings in results:
        if lang in scanned:
            scanned[lang] += 1
    out.append(
        "Scanned: "
        + ", ".join(f"{lang} {count} file(s)" for lang, count in scanned.items())
        + f", {sum(counts.values())} finding(s)."
    )
    out.append("")
    ranked = sorted(
        (item for item in results if item[2]),
        key=lambda item: (-len(item[2]), item[0]),
    )[:top]
    out.append("| file | lang | findings | fail-level |")
    out.append("|---|---|---:|---:|")
    for relative, lang, findings in ranked:
        fails = sum(1 for finding in findings if finding.level == "fail")
        out.append(f"| {relative} | {lang} | {len(findings)} | {fails} |")
    return "\n".join(out)


def selftest() -> int:
    failures: list[str] = []
    for rule in RULES:
        if not rule.positive or not rule.negative:
            failures.append(f"{rule.id}: needs a positive and a negative example")
        for lang, document in rule.positive:
            if rule.id not in {f.rule for f in scan_markdown(document, lang)}:
                failures.append(f"{rule.id}: silent on its positive {document[:40]!r}")
        for lang, document in rule.negative:
            if rule.id in {f.rule for f in scan_markdown(document, lang)}:
                failures.append(f"{rule.id}: fires on its negative {document[:40]!r}")
    if (
        len(
            unrendered_strong(
                "上は**「自分の構成」**で引く。次は**自分の構成**で引く。\n"
            )
        )
        < 1
    ):
        failures.append("D1: the bracketed-bold sentence is not reported")
    for failure in failures:
        print(f"selftest: {failure}", file=sys.stderr)
    if failures:
        return 1
    print(
        f"selftest: {len(RULES)} rule(s) fire on their positives and not their negatives"
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument(
        "paths", nargs="*", type=Path, help="files or directories (*.md)"
    )
    parser.add_argument(
        "--summary", action="store_true", help="print a Markdown count table"
    )
    parser.add_argument("--top", type=int, default=10, help="files listed in --summary")
    parser.add_argument(
        "--fail", action="store_true", help="exit 1 on a fail-level finding"
    )
    parser.add_argument(
        "--exclude", action="append", default=[], help="glob, relative path"
    )
    parser.add_argument(
        "--selftest", action="store_true", help="check every rule's examples"
    )
    args = parser.parse_args(argv)
    if args.selftest:
        return selftest()
    if not args.paths:
        parser.error("give at least one file or directory, or --selftest")
    results: list[tuple[str, str, list[Finding]]] = []
    for path, relative in _iter_markdown(args.paths, args.exclude):
        lang, findings = scan_file(path, relative)
        results.append((relative, lang, findings))
    if args.summary:
        print(summarize(results, args.top))
    else:
        for relative, _lang, findings in results:
            for finding in findings:
                category = CATEGORY_FOR_LEVEL[finding.level]
                print(
                    f"{relative}:{finding.line}: [{category}] {finding.rule} {finding.message}"
                )
    has_fail = any(f.level == "fail" for _r, _l, findings in results for f in findings)
    return 1 if args.fail and has_fail else 0


if __name__ == "__main__":
    sys.exit(main())
