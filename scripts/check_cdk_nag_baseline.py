# Why an IAM4 finding is recorded on a role we declare. It is one cause -- the role carries
# an AWS managed execution policy -- and the per-role entries in `REASONS` explain resource
# wildcards, which is a different question. Reading a role's IAM5 reason onto its IAM4
# finding would claim the managed policy was chosen for reasons about ARNs.
MANAGED_POLICY_REASON = (
    "An AWS managed execution policy on a Lambda role we declare: "
    "`AWSLambdaBasicExecutionRole` for CloudWatch Logs, and "
    "`AWSLambdaVPCAccessExecutionRole` on the one function that reaches the ONTAP "
    "management LIF. Both are the AWS-recommended policy for what they grant. Replacing "
    "the logs one with an inline policy needs the log group name, which derives from the "
    "function name CDK generates -- so the wildcard moves from the policy to the resource "
    "rather than going away."
)

# Paths whose findings belong to whoever generated the construct, IAM4 included. Checked
# before the rule, because `MANAGED_POLICY_REASON` says "a role we declare" and these are
# roles Amplify and the CDK construct library declare.
GENERATED_ELSEWHERE = ("auth/", "data/amplifyData", "data/Custom::CDK", "data/LogRetention")


def reason_for(path: str, rule: str = "") -> str:
    """The recorded reason for a finding.

    `rule` participates because one construct produces findings with unrelated causes: a
    role's resource wildcard and the managed policy attached to it are both reported
    against the role, and only the first is about what the role may reach.
    """
    generated = any(path.startswith(p) or p in path for p in GENERATED_ELSEWHERE)
    if rule.startswith("AwsSolutions-IAM4") and not generated:
        return MANAGED_POLICY_REASON
    for prefix, reason in REASONS:
        if path.startswith(prefix) or prefix in path:
            return reason
    return "uncategorised"


def run_nag() -> None:
    """Synthesise with cdk-nag. Does not deploy."""
    print("Running npm run nag (synthesises, does not deploy)...", file=sys.stderr)
    # The script exits non-zero while findings remain, which is the normal state and not
    # a reason to stop here: the report it writes is what this check reads.
    subprocess.run(
        ["npm", "run", "--silent", "nag"],
        cwd=PORTAL,
        check=False,
        capture_output=True,
        text=True,
    )


def current_findings() -> set[tuple[str, str]]:
    """Every (rule, construct path) cdk-nag reports, with the stack prefix removed.

    The stack name carries a hash of the backend identifier, which differs between a
    sandbox and CI, so it cannot be part of a finding's identity.
    """
    if not REPORT.is_file():
        run_nag()
    if not REPORT.is_file():
        raise SystemExit(f"no validation report at {REPORT}; run `npm run nag` in {PORTAL}")
    report = json.loads(REPORT.read_text())
    found: set[tuple[str, str]] = set()
    for plugin in report.get("pluginReports", []):
        for violation in plugin.get("violations", []):
            for construct in violation.get("violatingConstructs", []):
                path = construct["constructPath"]
                found.add((violation["ruleName"], path.split("/", 1)[1] if "/" in path else path))
    return found


def read_baseline() -> set[tuple[str, str]]:
    """The recorded findings. Empty when the file is absent."""
    if not BASELINE.is_file():
        return set()
    entries: set[tuple[str, str]] = set()
    for line in BASELINE.read_text().splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        rule, _, path = line.partition("\t")
        entries.add((rule, path))
    return entries


def write_baseline(findings: set[tuple[str, str]]) -> None:
    """Rewrite the baseline, grouped by reason so the diff is readable."""
    by_reason: dict[str, list[tuple[str, str]]] = {}
    for rule, path in findings:
        by_reason.setdefault(reason_for(path, rule), []).append((rule, path))
    lines = [
        "# cdk-nag findings recorded as known, one per line: <rule id>\\t<construct path>.",
        "#",
        "# Generated by `python3 scripts/check_cdk_nag_baseline.py --write`. A finding that",
        "# is not here fails the build, and an entry no longer reported fails too, so this",
        "# cannot drift upward or hide progress.",
        "#",
        "# The construct path has the stack name removed: it carries a hash of the backend",
        "# identifier, which differs between a sandbox and CI.",
        "#",
        "# A recorded finding is not a fixed one. The reason above each group is the whole",
        "# of what is claimed about it; see scripts/check_cdk_nag_baseline.py.",
    ]
    for reason in sorted(by_reason):
        lines.append("")
        for wrapped in _wrap(reason, 86):
            lines.append(f"# {wrapped}")
        for rule, path in sorted(by_reason[reason]):
            lines.append(f"{rule}\t{path}")
    BASELINE.parent.mkdir(parents=True, exist_ok=True)
    BASELINE.write_text("\n".join(lines) + "\n")


def _wrap(text: str, width: int) -> list[str]:
    """Wrap without importing textwrap, to keep the comment style predictable."""
    out: list[str] = []
    line = ""
    for word in text.split():
        if line and len(line) + 1 + len(word) > width:
            out.append(line)
            line = word
        else:
            line = f"{line} {word}".strip()
    if line:
        out.append(line)
    return out


def main(argv: list[str] | None = None) -> int:
    """Compare the report against the baseline.

    Args:
        argv: Arguments to parse. Defaults to the process arguments; passed explicitly by
            the tests, which would otherwise have pytest's own arguments parsed here.

    Returns:
        0 when the two agree, 1 when a finding is new, has been fixed without the baseline
        being refreshed, or no baseline is recorded at all.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--list", action="store_true", help="print what is reported now")
    parser.add_argument("--write", action="store_true", help="rewrite the baseline file")
    args = parser.parse_args(argv)

    findings = current_findings()

    if args.list:
        for rule, path in sorted(findings):
            print(f"{rule}\t{path}")
        print(f"\n{len(findings)} finding(s)", file=sys.stderr)
        return 0

    if args.write:
        write_baseline(findings)
        print(f"CDK-NAG BASELINE: wrote {len(findings)} finding(s) to {BASELINE.relative_to(ROOT)}")
        return 0

    baseline = read_baseline()
    if not baseline:
        print(
            "CDK-NAG BASELINE: FAIL (no baseline recorded; "
            "run `python3 scripts/check_cdk_nag_baseline.py --write` and read the diff)",
            file=sys.stderr,
        )
        return 1

    new = sorted(findings - baseline)
    fixed = sorted(baseline - findings)
    if new:
        print(f"CDK-NAG BASELINE: FAIL ({len(new)} finding(s) not in the baseline)")
        for rule, path in new:
            print(f"  NEW {rule}\n      {path}")
        print(
            "\nFix it, or record it with --write and say in the commit why it is acceptable.",
            file=sys.stderr,
        )
        return 1
    if fixed:
        print(f"CDK-NAG BASELINE: FAIL ({len(fixed)} baseline finding(s) no longer reported)")
        for rule, path in fixed:
            print(f"  GONE {rule}\n       {path}")
        print(
            "\nProgress the baseline does not know about. Refresh it with --write.",
            file=sys.stderr,
        )
        return 1

    print(f"CDK-NAG BASELINE: PASS ({len(findings)} known finding(s) at the baseline)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
