#!/usr/bin/env python3
"""Hold cdk-nag to a baseline, so a new finding fails instead of joining a pile.

Why a baseline rather than a clean run
--------------------------------------
cdk-nag reported 108 findings on the portal backend and nothing consumed the number, so
it was a report nobody read. Two of the categories were fixed rather than recorded
(point-in-time recovery on the two tables holding authored content, and a TLS-only policy
on the alarm topic). The rest need either a decision that cannot be validated without
deploying, or a change to a resource Amplify owns.

Recording them makes the remainder blocking: a finding that is not in the baseline fails,
and a baseline entry that is no longer reported also fails, so the file cannot drift
upward or hide progress. Same shape as `scripts/check_cfn_guard.py`.

What this does not claim
------------------------
A baselined finding is not a fixed finding. The `REASONS` table below says which
category each belongs to and why it is where it is; "Amplify owns the resource" and "we
own it and have not narrowed it yet" are different statements and are kept apart.

Running it
----------
    python3 scripts/check_cdk_nag_baseline.py            # blocking
    python3 scripts/check_cdk_nag_baseline.py --list     # what is reported now
    python3 scripts/check_cdk_nag_baseline.py --write    # rewrite the baseline file

`--write` is for after a deliberate change. Read the diff: it is the only place a new
finding can enter without failing.

The report comes from `solutions/amplify-portal/scripts/cdk-nag.sh` (`npm run nag`), which
synthesises without deploying. This script runs it when the report is missing or stale.
"""

